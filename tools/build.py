def modal_attr(url, label=""):
    """Mark a link to an embedded widget so site.js opens it over the page.

    Keyed on the path rather than a per-link flag: everything under /assets/interactive/ is a
    demo attached to a result, and none of them are places a reader means to navigate to.
    """
    if not str(url).startswith("/assets/interactive/"):
        return ""
    return f' data-modal="{e(label)}"' if label else " data-modal"


