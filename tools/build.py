def extra_meta(x):
    """Title, summary and count for a standalone page, taken from the page's own content
    file so a card can never advertise a different name from the page it links to."""
    d = json.loads((CONTENT / f"{x['content']}.json").read_text(encoding="utf-8"))
    return {
        "title": d["title"],
        "summary": d["lede"],
        "count": f'{plural(len(d["methods"]), "method")} on {len(d["sources"])} clips, '
                 "with every workflow and measurement",
    }


def timeline(cols):
    """Prompt collections and standalone pages in one list, newest first.

    The home page's "latest" and the projects grid both read from this, so a standalone
    page is ordered by its date like everything else instead of being pinned to the end.
    Each entry carries everything a card needs, whichever kind it came from.
    """
    items = [{
        "url": project_url(c),
        "title": c["title"],
        "summary": c["summary"][0],
        "count": f'{plural(len(c["prompts"]), "prompt")}, {e(" and ".join(c["models"]))}',
        "lead": f'{plural(len(c["prompts"]), "prompt")}, with reference images, settings and links',
        # No video yet: fall back to the collection's own card image, and no Watch link.
        "thumb": (video_thumb(c["video"]) if c.get("video")
                  else asset(f"img/{c['slug']}/card.jpg")),
        "published": c["published"],
        "watch": watch_url(c["video"]) if c.get("video") else None,
    } for c in cols]
    for x in EXTRA_PAGES:
        meta = extra_meta(x)
        items.append({
            "url": x["url"],
            "title": meta["title"],
            "summary": meta["summary"],
            "count": meta["count"],
            "lead": meta["count"],
            "thumb": x["thumb"],
            "published": x["published"],
            "watch": x.get("watch"),      # no video yet, so no Watch button
        })
    items.sort(key=lambda i: i["published"], reverse=True)
    return items


